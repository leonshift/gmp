module F32ToF16 (
    input [31:0] a,
    output logic [15:0] res
);
    logic sg;
    logic [7:0] e8;
    logic [22:0] m23;
    logic is_nan;
    logic is_inf;
    logic is_z;
    logic [9:0] e10;
    logic big;
    logic nrm_up;
    logic [15:0] nrm16;
    logic [23:0] full;
    logic [9:0] sh10;
    logic tiny;
    logic [9:0] kn;
    logic [3:0] k;
    logic [9:0] subq;
    logic [10:0] rnd;
    logic km_0;
    logic km_1;
    logic km_2;
    logic km_3;
    logic km_4;
    logic km_5;
    logic km_6;
    logic km_7;
    logic km_8;
    logic km_9;
    logic [9:0] kmask;
    logic sticky;
    logic sub_up;
    logic [15:0] sub16;
    logic is_sub;
    logic [14:0] m15;

    assign sg = a[31];
    assign e8 = a[30:23];
    assign m23 = a[22:0];
    assign is_nan = ((e8 == 255) & (m23 != 0));
    assign is_inf = ((e8 == 255) & (m23 == 0));
    assign is_z = (e8 == 0);
    assign e10 = ({2'd0, e8} - 10'd112);
    assign big = ((~e10[9]) & (e10 >= 31));
    assign nrm_up = (m23[12] & ((m23[11:0] != 0) | m23[13]));
    assign nrm16 = ({1'd0, e10[4:0], m23[22:13]} + {15'd0, nrm_up});
    assign full = {1'd1, m23};
    assign sh10 = (10'd14 - e10);
    assign tiny = (sh10 >= 25);
    assign kn = (10'd0 - e10);
    assign k = kn[3:0];
    assign subq = (full[23:14] >> k);
    assign rnd = (full[23:13] >> k);
    assign km_0 = (4'd0 < k);
    assign km_1 = (4'd1 < k);
    assign km_2 = (4'd2 < k);
    assign km_3 = (4'd3 < k);
    assign km_4 = (4'd4 < k);
    assign km_5 = (4'd5 < k);
    assign km_6 = (4'd6 < k);
    assign km_7 = (4'd7 < k);
    assign km_8 = (4'd8 < k);
    assign km_9 = (4'd9 < k);
    assign kmask = {km_9, km_8, km_7, km_6, km_5, km_4, km_3, km_2, km_1, km_0};
    assign sticky = ((m23[12:0] != 0) | ((m23[22:13] & kmask) != 0));
    assign sub_up = (rnd[0] & (sticky | subq[0]));
    assign sub16 = ({6'd0, subq} + {15'd0, sub_up});
    assign is_sub = (e10[9] | (e10 == 0));
    assign m15 = ((is_sub & tiny) ? 15'd0 : (is_sub ? sub16[14:0] : nrm16[14:0]));
    assign res = (is_nan ? 16'd32256 : ((is_inf | big) ? {sg, 15'd31744} : (is_z ? {sg, 15'd0} : {sg, m15})));
endmodule
